var update = flag.Bool("update", false, "rewrite testdata/<keyboard>.txt from this run")

const repo = "../.."

// TestConformance runs every keyboard of the CLDR corpus through the tool and compares the result with the
// committed testdata/<keyboard>.txt, so any change in what is imported, lost or typed fails (docs/cldr.md):
//
//   - import: `yakbd convert -tests` writes a schema-valid .kbl.json (the import's losses are recorded);
//   - round trip: .kbl.json → CLDR XML (and CLDR test files) → .kbl.json is equal: equal as JSON values
//     (kbljson.SameJSON: property order and white space ignored, an empty array or object counts as absent), the
//     tests included. Without the kbl <special> element (targets.cldr.carryInSpecial false) the paths that differ
//     are recorded: they are what plain CLDR elements cannot hold;
//   - tests: the CLDR test file becomes the file's tests, one test per <test> element;
//   - `yakbd validate -windows` and `yakbd compile` (LANGID LangID; again accepting Accepted when the plain build
//     fails) run, and their losses are recorded: severity, kind and location, no message text;
//   - every check of the tests becomes a case (Cases), typed by the emulator; the typed cases are what
//     tools/cldrbundle has a Windows guest type.
func TestConformance(t *testing.T) {
	ks, err := Keyboards(repo)
	if err != nil || len(ks) != 13 {
		t.Fatalf("corpus: %d keyboards, %v", len(ks), err)
	}
	withTests := 0
	for _, k := range ks {
		if k.TestPath != "" {
			withTests++
		}
		t.Run(k.Name, func(t *testing.T) {
			got := conformance(t, k)
			path := filepath.Join("testdata", k.Name+".txt")
			if *update {
				if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(path)
			if err != nil {
				t.Fatalf("%v (run go test ./convert/cldrconf -update)", err)
			}
			if got != string(want) {
				t.Errorf("differs from %s (go test ./convert/cldrconf -update, then review the diff):\n%s", path, lineDiff(string(want), got))
			}
		})
	}
	if withTests != 5 {
		t.Errorf("%d keyboards with a test file, want 5", withTests)
	}
}

func conformance(t *testing.T, k Keyboard) string {
	dir := t.TempDir()
	var b strings.Builder
	fmt.Fprintf(&b, "# CLDR conformance of %s.xml (CLDR release-49). Generated by go test ./convert/cldrconf -update.\n", k.Name)

	// Import.
	kblPath := filepath.Join(dir, k.Name+".kbl.json")
	args := []string{"convert", "-report", filepath.Join(dir, "import.json")}
	if k.TestPath != "" {
		args = append(args, "-tests", k.TestPath)
	}
	code, rep := runCLI(t, filepath.Join(dir, "import.json"), append(args, k.Path, kblPath)...)
	if code != 0 {
		t.Fatalf("import: exit %d\n%s", code, rep)
	}
	section(&b, "import", code, rep)
	data, err := os.ReadFile(kblPath)
	if err != nil {
		t.Fatal(err)
	}
	l, r := kbljson.Read(data, k.Name)
	if l == nil || r.HasErrors() {
		t.Fatalf("the import does not read back: %s", r.Summary())
	}

	// Round trip, with and without the kbl special.
	back := throughCLDR(t, l, true)
	if d := kbljson.DiffJSON(data, back); d != "" {
		t.Errorf("round trip: .kbl.json → CLDR → .kbl.json differs at %s", d)
		b.WriteString("round trip: differs\n")
	} else {
		b.WriteString("round trip: equal\n")
	}
	plain := throughCLDR(t, l, false)
	b.WriteString("round trip without the kbl special, paths that differ:")
	diffs := diffPaths(data, plain)
	if len(diffs) == 0 {
		b.WriteString(" none")
	}
	b.WriteString("\n")
	for _, d := range diffs {
		b.WriteString("  " + d + "\n")
	}

	// Tests.
	if k.TestPath != "" {
		x, _ := os.ReadFile(k.TestPath)
		n := 0
		for _, tf := range l.Tests {
			for _, s := range tf.Suites {
				n += len(s.Tests)
			}
		}
		if want := bytes.Count(x, []byte("<test ")); n != want || len(l.Tests) != 1 {
			t.Errorf("tests: %d tests in %d files, the CLDR test file has %d", n, len(l.Tests), want)
		}
		fmt.Fprintf(&b, "tests: %d from %s\n", n, filepath.Base(k.TestPath))
	} else {
		b.WriteString("tests: no CLDR test file\n")
	}

	// Validate and build.
	code, rep = runCLI(t, filepath.Join(dir, "validate.json"), "validate", "-windows", "-report", filepath.Join(dir, "validate.json"), kblPath)
	section(&b, "validate -windows", code, rep)
	cargs := []string{"compile", "-q", "-langid", LangID, "-o", filepath.Join(dir, "build"), "-report", filepath.Join(dir, "build.json")}
	code, rep = runCLI(t, filepath.Join(dir, "build.json"), append(cargs, kblPath)...)
	section(&b, "compile -langid "+LangID, code, rep)
	if code != 0 && hasAccepted(rep) {
		acc := strings.Join(Accepted, ",")
		code, rep = runCLI(t, filepath.Join(dir, "build.json"), append(cargs, "-accept", acc, kblPath)...)
		section(&b, "compile -langid "+LangID+" -accept "+acc, code, rep)
	}

	// Cases.
	res, br := Build(l)
	if res == nil {
		if code == 0 {
			t.Errorf("Build fails where the command line built: %s", br.Summary())
		}
		b.WriteString("cases: no build\n")
		return b.String()
	}
	cases := Cases(l, res)
	typed := 0
	var lines []wincheck.Line
	for _, c := range cases {
		b.WriteString(c.String() + "\n")
		if strings.Contains(c.Skip, "unexplained") {
			t.Errorf("%s: a difference no loss kind explains (a tool bug): %s", c.Name, c.Skip)
		}
		if c.Skip == "" {
			typed++
			lines = append(lines, c.Line())
		}
	}
	fmt.Fprintf(&b, "cases: %d typed, %d skipped\n", typed, len(cases)-typed)
	// The typed lines, read back as the guest reads them, pass the emulator.
	var text strings.Builder
	for _, l := range lines {
		text.WriteString(l.String() + "\n")
	}
	parsed, err := wincheck.ParseExpectations(strings.NewReader(text.String()))
	if err != nil || len(parsed) != typed {
		t.Fatalf("typed lines: %v", err)
	}
	if d := wincheck.Check(parsed, &wincheck.Emulator{T: &res.DLL.Tables}); len(d) > 0 {
		t.Errorf("the emulator fails %d typed cases, first %s", len(d), d[0])
	}
	return b.String()
}

// runCLI runs the command line and returns its exit code and the report it wrote, as sorted lines.
func runCLI(t *testing.T, report string, args ...string) (int, []string) {
	t.Helper()
	os.Remove(report)
	var o, e bytes.Buffer
	code := cli.Run(args, &o, &e)
	data, err := os.ReadFile(report)
	if err != nil {
		t.Fatalf("%v: no report (exit %d)\n%s", args, code, e.String())
	}
	var r jsonReport
	if err := json.Unmarshal(data, &r); err != nil {
		t.Fatalf("report: %v", err)
	}
	return code, reportLines(&r)
}

// reportLines are the losses and errors of a report: severity, kind and location (the file name dropped, it is a
// temporary path), sorted, with a count for repeats.
// jsonReport is the -report file (docs/report-file.md); a location is its pointer, else its path.
type jsonReport struct {
	Entries []struct {
		Class, Severity, Kind string
		Where                 struct {
			File, Path string
			Line       int
			Pointer    *string
		}
	}
}

func reportLines(r *jsonReport) []string {
	count := map[string]int{}
	for _, e := range r.Entries {
		if e.Class != loss.Loss.String() && e.Severity != loss.Error.String() {
			continue
		}
		w := loss.Where{Line: e.Where.Line, Path: e.Where.Path}
		if e.Where.Pointer != nil {
			w.Path = *e.Where.Pointer
		}
		s := e.Severity + " " + e.Kind
		if ws := w.String(); ws != "" {
			s += " " + ws
		}
		count[s]++
	}
	var out []string
	for s, n := range count {
		if n > 1 {
			s += fmt.Sprintf(" (×%d)", n)
		}
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func section(b *strings.Builder, name string, code int, lines []string) {
	fmt.Fprintf(b, "%s: exit %d, %d loss or error line(s)\n", name, code, len(lines))
	for _, l := range lines {
		b.WriteString("  " + l + "\n")
	}
}

// throughCLDR writes l as CLDR (its tests as CLDR test files), reads that back and returns the .kbl.json.
func throughCLDR(t *testing.T, l *model.Layout, carry bool) []byte {
	t.Helper()
	c := *l
	tg := model.Targets{}
	if l.Targets != nil {
		tg = *l.Targets
	}
	ct := model.CLDRTarget{}
	if tg.CLDR != nil {
		ct = *tg.CLDR
	}
	if !carry {
		ct.CarryInSpecial = &carry
		tg.CLDR = &ct
		c.Targets = &tg
	}
	x, _ := cldr.Write(&c)
	back, r := cldr.Read(x, l.Metadata.Provenance.Source)
	if back == nil {
		t.Fatalf("written CLDR (special %v) does not read back: %s", carry, r.Summary())
	}
	for _, tf := range l.Tests {
		tb, _ := cldr.WriteTests(tf)
		tests, tr := cldr.ReadTests(tb, tf.Info.Name)
		if tests == nil {
			t.Fatalf("tests: %s", tr.Summary())
		}
		back.Tests = append(back.Tests, tests...)
	}
	out, wr := kbljson.Write(back)
	if out == nil {
		t.Fatalf("read back from CLDR (special %v), not schema-valid: %s", carry, wr.Summary())
	}
	return out
}

// diffPaths lists the JSON Pointers where two documents differ in the sense of kbljson.SameJSON (at most one per
// array whose length differs).
func diffPaths(a, b []byte) []string {
	var x, y any
	json.Unmarshal(a, &x)
	json.Unmarshal(b, &y)
	var out []string
	var walk func(x, y any, at string)
	empty := func(v any) bool {
		switch v := v.(type) {
		case nil:
			return true
		case []any:
			return len(v) == 0
		case map[string]any:
			return len(v) == 0
		}
		return false
	}
	walk = func(x, y any, at string) {
		if empty(x) && empty(y) {
			return
		}
		switch xv := x.(type) {
		case map[string]any:
			yv, ok := y.(map[string]any)
			if !ok {
				out = append(out, at)
				return
			}
			keys := map[string]bool{}
			for k := range xv {
				keys[k] = true
			}
			for k := range yv {
				keys[k] = true
			}
			var ks []string
			for k := range keys {
				ks = append(ks, k)
			}
			sort.Strings(ks)
			for _, k := range ks {
				walk(xv[k], yv[k], at+"/"+k)
			}
		case []any:
			yv, ok := y.([]any)
			if !ok || len(yv) != len(xv) {
				out = append(out, at)
				return
			}
			for i := range xv {
				walk(xv[i], yv[i], fmt.Sprintf("%s/%d", at, i))
			}
		default:
			xb, _ := json.Marshal(x)
			yb, _ := json.Marshal(y)
			if !bytes.Equal(xb, yb) {
				out = append(out, at)
			}
		}
	}
	walk(x, y, "")
	return out
}

func lineDiff(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	var b strings.Builder
	in := map[string]bool{}
	for _, l := range g {
		in[l] = true
	}
	for _, l := range w {
		if !in[l] {
			b.WriteString("- " + l + "\n")
		}
	}
	in = map[string]bool{}
	for _, l := range w {
		in[l] = true
	}
	for _, l := range g {
		if !in[l] {
			b.WriteString("+ " + l + "\n")
		}
	}
	return b.String()
}

// TestImportsEqualTheCorpus: the import files the reader embeds are the corpus's, byte for byte.
func TestImportsEqualTheCorpus(t *testing.T) {
	files, _ := filepath.Glob(filepath.Join(repo, "format/cldr/import/*.xml"))
	corpus, _ := filepath.Glob(filepath.Join(repo, Corpus, "import/*.xml"))
	if len(files) != 4 || len(corpus) != 4 {
		t.Fatalf("%d embedded, %d in the corpus", len(files), len(corpus))
	}
	for _, f := range files {
		a, _ := os.ReadFile(f)
		b, err := os.ReadFile(filepath.Join(repo, Corpus, "import", filepath.Base(f)))
		if err != nil || !bytes.Equal(a, b) {
			t.Errorf("%s differs from the corpus copy (%v)", filepath.Base(f), err)
		}
	}
}

// hasAccepted reports an error line of one of the Accepted kinds: the build is then run again accepting them.
func hasAccepted(lines []string) bool {
	for _, l := range lines {
		for _, k := range Accepted {
			if strings.HasPrefix(l, "error "+k+" ") || l == "error "+k {
				return true
			}
		}
	}
	return false
}
